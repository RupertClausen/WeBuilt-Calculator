"""Plate pictures: extracted per plate, stored with the quote, shown on the
calculator and the receipt."""
import base64, json, os, pathlib, sqlite3, sys, tempfile
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

ROOT = pathlib.Path(__file__).resolve().parents[1]
FX = ROOT / "tests" / "fixtures"
os.environ["WEBUILT_DB"] = str(pathlib.Path(tempfile.mkdtemp()) / "orders.db")

from fastapi.testclient import TestClient
import app as appmod
import slicefile
from make_thumbnail_fixtures import png, gcode_block

client = TestClient(appmod.app)


def first_pixel(data: bytes) -> tuple[int, int, int]:
    import zlib
    raw = zlib.decompressobj().decompress(data[data.index(b"IDAT") + 4:])
    return tuple(raw[1:4])


def upload(names, **data):
    files = [("files", (n, (FX / n).read_bytes())) for n in names]
    r = client.post("/api/quote", files=files, data=data)
    assert r.status_code == 200, r.text
    return r.json()


# --- parser -----------------------------------------------------------------

def test_3mf_gives_each_plate_its_own_picture():
    jobs = slicefile.parse("x.gcode.3mf", (FX / "bambu_two_plates.gcode.3mf").read_bytes())
    assert [j.plate_index for j in jobs] == [1, 2]
    assert first_pixel(jobs[0].thumbnail) == (220, 40, 40)      # plate_1.png, red
    assert first_pixel(jobs[1].thumbnail) == (40, 80, 220)      # plate_2.png, blue
    assert all(j.thumbnail_mime == "image/png" for j in jobs)
    print("  3mf             plate 1 red, plate 2 blue — matched by plate number")


def test_gcode_takes_largest_displayable_picture():
    (job,) = slicefile.parse("x.gcode", (FX / "orca_with_thumbnail.gcode").read_bytes())
    assert first_pixel(job.thumbnail) == (40, 170, 70)          # the 96px one
    assert job.total_grams == 42.0 and abs(job.hours - 2.0833) < 0.01
    print("  gcode           largest PNG chosen, QOI skipped, settings still parsed")


def test_files_without_pictures_still_quote():
    (job,) = slicefile.parse("x.gcode", (FX / "orca_petg_single.gcode").read_bytes())
    assert job.thumbnail is None and job.thumbnail_mime is None
    print("  no picture      thumbnail None, file still parses")


def test_only_real_png_or_jpeg_is_kept():
    junk = b"<svg onload=alert(1)>" + b"x" * 50
    g = ("; generated by OrcaSlicer\n" + gcode_block("thumbnail", 10, 10, junk)
         + "; filament used [g] = 1\n; estimated printing time (normal mode) = 5m\n"
           "; filament_type = PLA\n")
    (job,) = slicefile.parse("x.gcode", g.encode())
    assert job.thumbnail is None
    big = png(1, 1, (0, 0, 0)) + b"\x00" * (slicefile.MAX_THUMBNAIL_BYTES + 1)
    assert slicefile._usable(big) is None
    assert slicefile.image_mime(b"\xff\xd8\xff\xe0rest") == "image/jpeg"
    print("  type check      SVG/garbage rejected by bytes, oversize rejected, JPEG accepted")


# --- storage and API ----------------------------------------------------------

def test_saved_quote_serves_each_plate_picture():
    d = upload(["bambu_two_plates.gcode.3mf", "orca_petg_single.gcode"])
    qid, plates = d["quote_id"], d["breakdown"]["plates"]
    assert plates[0]["thumbnail"] == f"/api/orders/{qid}/plates/1/thumbnail"
    assert plates[1]["thumbnail"] == f"/api/orders/{qid}/plates/2/thumbnail"
    assert plates[2]["thumbnail"] is None
    r = client.get(plates[1]["thumbnail"])
    assert r.status_code == 200 and r.headers["content-type"] == "image/png"
    assert r.headers["x-content-type-options"] == "nosniff"
    assert first_pixel(r.content) == (40, 80, 220)
    assert client.get(f"/api/orders/{qid}/plates/3/thumbnail").status_code == 404
    print("  served          plates 1-2 served as PNG with nosniff, plate 3 404s")


def test_unsaved_quote_carries_pictures_inline():
    d = upload(["orca_with_thumbnail.gcode"], save="false")
    t = d["breakdown"]["plates"][0]["thumbnail"]
    assert t.startswith("data:image/png;base64,")
    assert first_pixel(base64.b64decode(t.split(",", 1)[1])) == (40, 170, 70)
    print("  unsaved         picture returned inline as a data URI")


def test_manual_quotes_have_no_pictures():
    d = client.post("/api/quote/manual", json={
        "filaments": [{"type": "PLA", "grams": 10}], "hours": 1, "save": True}).json()
    assert d["breakdown"]["plates"][0]["thumbnail"] is None
    print("  manual          thumbnail field present, empty")


def test_pictures_stay_out_of_the_quote_record():
    """Images go in their own table; the stored quote JSON must not grow."""
    d = upload(["bambu_two_plates.gcode.3mf"])
    with sqlite3.connect(appmod.DB_PATH) as c:
        detail = c.execute("SELECT detail_json FROM quotes WHERE id = ?",
                           (d["quote_id"],)).fetchone()[0]
        n = c.execute("SELECT count(*) FROM plate_thumbnails WHERE quote_id = ?",
                      (d["quote_id"],)).fetchone()[0]
    assert "base64" not in detail and "thumbnail" not in detail and n == 2
    print(f"  storage         2 pictures in plate_thumbnails, none in detail_json")


def test_deleting_a_quote_deletes_its_pictures():
    d = upload(["bambu_two_plates.gcode.3mf"])
    with appmod.db() as c:
        c.execute("DELETE FROM quotes WHERE id = ?", (d["quote_id"],))
        n = c.execute("SELECT count(*) FROM plate_thumbnails WHERE quote_id = ?",
                      (d["quote_id"],)).fetchone()[0]
    assert n == 0
    print("  cascade         deleting a quote removes its pictures")


# --- receipt ------------------------------------------------------------------

def test_receipt_shows_a_picture_per_plate_in_both_languages():
    d = upload(["bambu_two_plates.gcode.3mf", "orca_petg_single.gcode"])
    qid = d["quote_id"]
    for lang, placeholder in (("en", "No picture in the file"),
                              ("th", "ไฟล์นี้ไม่มีภาพตัวอย่าง")):
        v = client.get(f"/api/receipt/{qid}?lang={lang}").json()
        assert [p["thumbnail"] for p in v["plates"]] == [
            f"/api/orders/{qid}/plates/1/thumbnail",
            f"/api/orders/{qid}/plates/2/thumbnail", None]
        html = client.get(f"/receipt/{qid}?lang={lang}").text
        assert html.count('<img src="/api/orders/') == 2
        assert placeholder in html
    print("  receipt         2 pictures + 1 placeholder, in English and Thai")


