"""Build the thumbnail test fixtures. Run once; the outputs are committed.

PNGs are written by hand with zlib so the project needs no image library.
"""
import base64, io, pathlib, struct, zipfile, zlib

FX = pathlib.Path(__file__).parent / "fixtures"


def png(w: int, h: int, rgb: tuple[int, int, int]) -> bytes:
    def chunk(kind, data):
        c = struct.pack(">I", len(data)) + kind + data
        return c + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    row = b"\x00" + bytes(rgb) * w
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(row * h))
            + chunk(b"IEND", b""))


def gcode_block(label: str, w: int, h: int, data: bytes) -> str:
    b64 = base64.b64encode(data).decode()
    body = "\n".join("; " + b64[i:i + 78] for i in range(0, len(b64), 78))
    return f"; {label} begin {w}x{h} {len(b64)}\n{body}\n; {label} end\n"


def slice_info(plates):
    rows = []
    for idx, secs, grams, typ in plates:
        rows.append(f"""  <plate>
    <metadata key="index" value="{idx}"/>
    <metadata key="printer_model_id" value="C11"/>
    <metadata key="prediction" value="{secs}"/>
    <metadata key="weight" value="{grams}"/>
    <filament id="1" type="{typ}" color="#808080" used_m="1" used_g="{grams}"/>
  </plate>""")
    return '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n' + "\n".join(rows) + "\n</config>\n"


def main():
    # Two plates in one export, each with its own picture (red, blue).
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("3D/3dmodel.model", "<model/>")
        z.writestr("Metadata/slice_info.config",
                   slice_info([(1, 7200, 80.5, "PLA"), (2, 18000, 150.25, "PETG")]))
        z.writestr("Metadata/plate_1.png", png(64, 64, (220, 40, 40)))
        z.writestr("Metadata/plate_1_small.png", png(16, 16, (220, 40, 40)))
        z.writestr("Metadata/plate_2.png", png(64, 64, (40, 80, 220)))
    (FX / "bambu_two_plates.gcode.3mf").write_bytes(buf.getvalue())

    # Plain gcode with a small and a large PNG, plus a QOI block browsers
    # cannot show. The large PNG (green) must win; QOI must be ignored.
    g = ("; generated by OrcaSlicer 2.1.1\n; THUMBNAIL_BLOCK_START\n"
         + gcode_block("thumbnail", 16, 16, png(16, 16, (200, 200, 200)))
         + gcode_block("thumbnail", 96, 96, png(96, 96, (40, 170, 70)))
         + gcode_block("thumbnail_QOI", 300, 300, b"qoif" + b"\x00" * 64)
         + "; THUMBNAIL_BLOCK_END\n"
         "G90\nM83\n"
         "; filament used [g] = 42.00\n"
         "; estimated printing time (normal mode) = 2h 5m 0s\n"
         "; filament_type = PLA\n"
         "; printer_model = Bambu Lab P1S\n")
    (FX / "orca_with_thumbnail.gcode").write_text(g)
    print("written:", "bambu_two_plates.gcode.3mf", "orca_with_thumbnail.gcode")


if __name__ == "__main__":
    main()
